-- Contenido clínico -----------------------------------------------------------

create table grafo_clinico_entity (
    id bigint generated by default as identity,
    estructura jsonb not null,
    jpa_version bigint,
    primary key (id)
);

create table base_reglas_entity (
    id bigint generated by default as identity,
    estructura jsonb not null,
    jpa_version bigint,
    primary key (id)
);

create table version_contenido (
    id bigint generated by default as identity,
    grafo jsonb not null,
    reglas jsonb,
    creada_en timestamp(6) with time zone not null,
    origen varchar(255) not null,
    primary key (id)
);

-- Seguridad -------------------------------------------------------------------

create table usuario (
    id bigint generated by default as identity,
    correo varchar(255) not null,
    nombre varchar(255) not null,
    hash_contrasena varchar(255) not null,
    rol varchar(255) not null check (rol in ('PADRE', 'MEDICO', 'MEDICO_SUPERVISOR')),
    institucion varchar(255),
    activo boolean not null,
    creado_en timestamp(6) with time zone,
    sesion_valida_desde timestamp(6) with time zone,
    primary key (id),
    constraint uk_usuario_correo unique (correo)
);

-- Recorridos y observaciones --------------------------------------------------

create table recorrido (
    id varchar(255) not null,
    usuario_id bigint not null,
    estado varchar(255) not null,
    nivel varchar(255),
    mensaje varchar(2000),
    iniciado_en timestamp(6) with time zone not null,
    finalizado_en timestamp(6) with time zone,
    primary key (id)
);

-- ObservacionEntity usa GenerationType.AUTO: Hibernate reserva ids de a 50.
create sequence observacion_entity_seq start with 1 increment by 50;

create table observacion_entity (
    id bigint not null,
    recorrido_id varchar(255),
    usuario_id bigint,
    id_nodo varchar(255),
    tipo varchar(255) check (tipo in ('SI_NO', 'SELECCION_UNICA', 'SELECCION_MULTIPLE')),
    timestamp timestamp(6) with time zone,
    primary key (id)
);

create table observacion_opciones (
    observacion_id bigint not null,
    opciones_seleccionadas varchar(255),
    constraint fk_observacion_opciones_observacion
        foreign key (observacion_id) references observacion_entity
);

-- Autoría ---------------------------------------------------------------------

create table borrador_subgrafo_entity (
    id bigint generated by default as identity,
    grafo_id varchar(255) not null,
    nombre varchar(255) not null,
    puente_id varchar(255) not null,
    categoria varchar(255) not null,
    etiqueta_opcion varchar(255) not null,
    autor varchar(255),
    institucion varchar(255),
    autor_id bigint,
    documento jsonb not null,
    estado varchar(255) not null
        check (estado in ('BORRADOR', 'PUBLICADO', 'CAMBIOS_SIN_PUBLICAR', 'EN_REVISION')),
    creado_en timestamp(6) with time zone,
    actualizado_en timestamp(6) with time zone,
    publicado_en timestamp(6) with time zone,
    copia_publicada jsonb,
    enviado_revision_en timestamp(6) with time zone,
    revisor_id bigint,
    revisado_en timestamp(6) with time zone,
    comentario_revision varchar(2000),
    jpa_version bigint,
    primary key (id),
    constraint uk_borrador_subgrafo_grafo_id unique (grafo_id)
);

create table borrador_base_regla_entity (
    id bigint generated by default as identity,
    grafo_id varchar(255) not null,
    nombre varchar(255) not null,
    descripcion varchar(255),
    autor varchar(255),
    institucion varchar(255),
    autor_id bigint,
    documento jsonb not null,
    estado varchar(255) not null
        check (estado in ('BORRADOR', 'PUBLICADO', 'CAMBIOS_SIN_PUBLICAR', 'EN_REVISION')),
    creado_en timestamp(6) with time zone,
    actualizado_en timestamp(6) with time zone,
    publicado_en timestamp(6) with time zone,
    copia_publicada jsonb,
    jpa_version bigint,
    primary key (id),
    constraint uk_borrador_base_regla_grafo_id unique (grafo_id)
);
