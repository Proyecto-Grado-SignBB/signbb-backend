-- =============================================================================
-- V3: límites de intentos de ingreso y de registro
-- =============================================================================
-- Los contadores viven en PostgreSQL para que el límite no dependa de Redis y
-- sobreviva a reinicios del backend. La clave es un hash del correo
-- normalizado: no se guarda el correo en claro. El tipo distingue el límite de
-- ingreso (LOGIN_CUENTA) del de registro (REGISTRO_CUENTA).
-- =============================================================================

create table limite_intentos (
    id bigint generated by default as identity,
    tipo varchar(20) not null,
    clave varchar(64) not null,
    contador integer not null,
    ventana_inicio timestamp(6) with time zone not null,
    bloqueado_hasta timestamp(6) with time zone,
    expira_en timestamp(6) with time zone not null,
    actualizado_en timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_limite_intentos unique (tipo, clave),
    constraint ck_limite_intentos_tipo check (tipo in ('LOGIN_CUENTA', 'REGISTRO_CUENTA')),
    constraint ck_limite_intentos_contador check (contador > 0)
);

create index idx_limite_intentos_expira on limite_intentos (expira_en);
